// ==========================================
// NODE.JS - PROCESS OBJECT
// ==========================================

// Node.js provides a built-in global object called 'process'.
// The process object provides information about and control over the current Node.js process.
// A Node.js process is the running instance of a Node.js program.

// ------------------------------------------
// Displaying the Process Object
// ------------------------------------------

// We can use console.log() to display the process object.

console.log(process);


// ------------------------------------------
// What does process contain?
// ------------------------------------------

// The process object contains information related to the currently running Node.js process.
// It provides properties and methods related to:
// - Node.js version
// - Operating system
// - Environment
// - Current working directory
// - Command-line arguments
// - Process execution


// ------------------------------------------
// Important
// ------------------------------------------

// 'process' is provided by Node.js automatically. We do not need to import or require it.

// Example:
// console.log(process);

// This will display a large object containing information about the current Node.js process.


