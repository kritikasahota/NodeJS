// ------------------------------------------
// Node.js Version
// ------------------------------------------

// process.version returns the version of Node.js that is currently installed and running.

console.log(process.version);


// ------------------------------------------
// Operating System Platform
// ------------------------------------------

// process.platform returns the operating system platform on which the Node.js process is running.
// For example:
// Windows → win32

console.log(process.platform);

// ------------------------------------------
// System Architecture
// ------------------------------------------

// process.arch returns the CPU architecture for which the Node.js process is running.
// For example:
// x64 → 64-bit architecture

console.log(process.arch);


