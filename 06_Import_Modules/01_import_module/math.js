// ==========================================
// ES MODULES - EXPORT
// ==========================================

// ES Modules use the 'export' keyword to make variables, functions, or other values available to other JavaScript files.

export function add(a, b) {
    return a + b;
}

export function subtract(a, b) {
    return a - b;
}

export function multiply(a, b) {
    return a * b;
}