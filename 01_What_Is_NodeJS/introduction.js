// Node.js is a JavaScript runtime environment.
// It allows us to execute JavaScript outside the browser.
//
// Normally, JavaScript runs inside a browser.
// Node.js allows JavaScript to run on the server/computer without requiring a browser.
// Node.js is built on Chrome's V8 JavaScript engine.

// --------------------------------------------------
// Running JavaScript with Node.js
// --------------------------------------------------

// We can create a .js file and execute it using: node filename.js
// Example: node introduction.js

console.log("Hello from Node.js");

// --------------------------------------------------
// JavaScript Outside the Browser
// --------------------------------------------------
// The following JavaScript code is being executed by Node.js instead of a browser.

console.log("JavaScript is running outside the browser");

// --------------------------------------------------
// Variables in Node.js
// --------------------------------------------------

// Node.js can execute normal JavaScript code.
// Here, we create a variable using let.

let name = "Kritika";
console.log(name);
